// A classe Produto é um "molde" para criar objetos que representam produtos.
//
// A classe define quais informações (atributos) cada produto terá.
public class Produto {

// Atributos da classe Produto.
// Cada objeto Produto terá seus próprios valores para esses atributos.

// Nome do produto.
	String nome;

// Descrição do produto.
	String descricao;

// Preço de uma unidade do produto.
// O tipo double permite armazenar números com casas decimais.
	double precoUnitario;

// Percentual de desconto do produto.
// Por exemplo: 10 representa 10% de desconto.
	int desconto;
}