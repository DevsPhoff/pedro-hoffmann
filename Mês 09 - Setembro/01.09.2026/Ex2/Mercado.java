// A classe Mercado é um "molde" que representa um mercado.
// Ela define quais informações cada unidade de mercado terá.
public class Mercado {

// Atributos (características) de um objeto Mercado.

// Guarda o nome do mercado.
	String nomeMercado;

// Guarda a quantidade de maçãs vendidas.
	int macasVendidas;

// Guarda o preço de cada maçã.
	double precoMaca;

// Guarda a quantidade de laranjas vendidas.
	int laranjasVendidas;

// Guarda o preço de cada laranja.
	double precoLaranja;
}